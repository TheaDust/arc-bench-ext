// requirement: REQ-2.10
import { test, expect, action, note, section, openHome, navigate, createNote, createLabel, deleteNote,
  archiveNote, expectNote, expectNoteInCollection, expectVisibleText } from './helpers';
import { identity } from './fixtures/data';
import { expectLightGreenSurface } from './visual';

test('REQ-2.10: Restore an active note with its saved attributes', async ({ page }, info) => {
  await openHome(page);
  const title = identity(info, 'Restore pinned note');
  const other = identity(info, 'Keep in Trash');
  const label = identity(info, 'Restore label');
  await createLabel(page, label);
  await createNote(page, title, 'Restore all saved attributes', { pinned: true, green: true, labels: [label] });
  await createNote(page, other, 'Other deleted content');
  await deleteNote(page, title);
  await deleteNote(page, other);
  await navigate(page, 'Trash');
  await expectNoteInCollection(page, 'Deleted notes', title, 'Restore all saved attributes');
  await expectNoteInCollection(page, 'Deleted notes', other, 'Other deleted content');
  await note(page, title).hover();
  await action(note(page, title), `Restore ${title}`).click();
  await expect(note(page, title)).toBeHidden();
  await expectNoteInCollection(page, 'Deleted notes', other, 'Other deleted content');
  await navigate(page, 'Notes');
  await page.reload();
  await expectNoteInCollection(page, 'Pinned notes', title, 'Restore all saved attributes');
  await expect(section(page, 'Other notes').getByRole('region', { name: title, exact: true })).toHaveCount(0);
  await expectVisibleText(note(page, title), label);
  await note(page, title).hover();
  await expect(action(note(page, title), `Unpin ${title}`)).toHaveAttribute('aria-pressed', 'true');
  await expect(action(note(page, title), `Background color ${title}: Light green`)).toBeVisible();
  await expectLightGreenSurface(note(page, title));
  await navigate(page, label);
  await expectNote(page, title, 'Restore all saved attributes');
  await expect(note(page, other)).toBeHidden();
  await navigate(page, 'Archived');
  await expect(section(page, 'Archived notes')).toHaveCount(1);
  await expect(note(page, title)).toBeHidden();
  await navigate(page, 'Trash');
  await expect(section(page, 'Deleted notes')).toHaveCount(1);
  await expect(note(page, title)).toBeHidden();
  await expectNoteInCollection(page, 'Deleted notes', other, 'Other deleted content');
});

test('REQ-2.10: Restore a deleted archived note to Archived', async ({ page }, info) => {
  await openHome(page);
  const title = identity(info, 'Restore archived note');
  const active = identity(info, 'Active restore control');
  const label = identity(info, 'Archived restore label');
  await createLabel(page, label);
  await createNote(page, title, 'Return to the archived collection', { labels: [label] });
  await createNote(page, active, 'Keep this active note');
  await archiveNote(page, title);
  await navigate(page, 'Archived');
  await expectNoteInCollection(page, 'Archived notes', title, 'Return to the archived collection');
  await deleteNote(page, title);
  await navigate(page, 'Trash');
  await expectNoteInCollection(page, 'Deleted notes', title, 'Return to the archived collection');
  await note(page, title).hover();
  await action(note(page, title), `Restore ${title}`).click();
  await expect(note(page, title)).toBeHidden();
  await navigate(page, 'Archived');
  await page.reload();
  await expectNoteInCollection(page, 'Archived notes', title, 'Return to the archived collection');
  await expectVisibleText(note(page, title), label);
  await expect(note(page, active)).toBeHidden();
  await navigate(page, label);
  await expect(note(page, title)).toBeHidden();
  await navigate(page, 'Notes');
  await expect(note(page, title)).toBeHidden();
  await expectNote(page, active, 'Keep this active note');
  await navigate(page, 'Archived');
  await note(page, title).hover();
  await action(note(page, title), `Unarchive ${title}`).click();
  await navigate(page, label);
  await expectNote(page, title, 'Return to the archived collection');
  await expectVisibleText(note(page, title), label);
  await expect(note(page, active)).toBeHidden();
  await navigate(page, 'Trash');
  await expect(section(page, 'Deleted notes')).toHaveCount(1);
  await expect(note(page, title)).toBeHidden();
});
