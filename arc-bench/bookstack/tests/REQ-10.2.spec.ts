// requirement: REQ-10.2
import { test, expect } from '@playwright/test';
import { button, createBook, createChapter, createPage, createPageInChapter, enter, entry, expectAbsentEntry, favorite,
  heading, home, identity, login, openBook, openChapter, openPageInChapter, region, text } from './helpers';

test("REQ-10.2: Confirm chapter deletion", async ({ page }, testInfo) => {
  const id = identity(testInfo);
  await enter(page);
  await login(page);
  const book = await createBook(page, id, 'Book 10.2.1');
  const chapter = await createChapter(page, id, book, 'Chapter 10.2.1');
  const pageA = await createPageInChapter(page, id, book, chapter, 'Page 10.2.1-A', 'Page content 10.2.1-A.');
  const pageB = await createPageInChapter(page, id, book, chapter, 'Page 10.2.1-B', 'Page content 10.2.1-B.');
  const root = await createPage(page, id, book, 'Page 10.2.1-Root', 'Root content 10.2.1.');
  const otherChapter = await createChapter(page, id, book, 'Chapter 10.2.1-Other');
  const otherPage = await createPageInChapter(page, id, book, otherChapter, 'Page 10.2.1-Other-Page', 'Other content 10.2.1.');
  await openChapter(page, book, chapter);
  await favorite(page);
  await openPageInChapter(page, book, chapter, pageA);
  await favorite(page);
  const pageUrl = page.url();
  await home(page);
  await expect(entry(region(page, 'Recently Updated Pages'), pageA)).toHaveCount(1);
  await expect(entry(region(page, 'My Most Viewed Favorites'), chapter)).toHaveCount(1);
  await expect(entry(region(page, 'My Most Viewed Favorites'), pageA)).toHaveCount(1);
  await openChapter(page, book, chapter);
  await button(page, 'Delete').click();
  await expect(button(page, 'Cancel')).toBeVisible();
  await expect(button(page, 'Confirm Delete')).toBeVisible();
  await button(page, 'Confirm Delete').click();
  await heading(page, book);
  await expectAbsentEntry(region(page, 'Chapter list'), chapter);
  await expect(entry(region(page, 'Chapter list'), otherChapter)).toHaveCount(1);
  await expectAbsentEntry(region(page, 'Page list'), pageA);
  await expectAbsentEntry(region(page, 'Page list'), pageB);
  await expect(entry(region(page, 'Page list'), root)).toHaveCount(1);
  await openChapter(page, book, otherChapter);
  await expect(entry(region(page, 'Page list'), otherPage)).toHaveCount(1);
  await home(page);
  await expectAbsentEntry(region(page, 'Recently Updated Pages'), pageA);
  await expectAbsentEntry(region(page, 'Recently Updated Pages'), pageB);
  await expect(entry(region(page, 'Recently Updated Pages'), root)).toHaveCount(1);
  await expectAbsentEntry(region(page, 'My Most Viewed Favorites'), chapter);
  await expectAbsentEntry(region(page, 'My Most Viewed Favorites'), pageA);
  await expectAbsentEntry(region(page, 'My Recently Viewed'), chapter);
  await expectAbsentEntry(region(page, 'My Recently Viewed'), pageA);
  await page.goto(pageUrl);
  await expect(page.getByRole('textbox', { name: 'Page title', exact: true })).toHaveCount(0);
  await expect(page.getByText('Page content 10.2.1-A.', { exact: true })).toHaveCount(0);
  await openBook(page, book);
  await page.reload();
  await expectAbsentEntry(region(page, 'Chapter list'), chapter);
  await expectAbsentEntry(region(page, 'Page list'), pageA);
});

test("REQ-10.2: Cancel chapter deletion", async ({ page }, testInfo) => {
  const id = identity(testInfo);
  await enter(page);
  const book = await createBook(page, id, 'Book 10.2.2');
  const chapter = await createChapter(page, id, book, 'Chapter 10.2.2');
  const pageA = await createPageInChapter(page, id, book, chapter, 'Page 10.2.2', 'Page content 10.2.2.');
  await openChapter(page, book, chapter);
  await button(page, 'Delete').click();
  await button(page, 'Cancel').click();
  await heading(page, chapter);
  await text(page, 'Chapter created by corresponding prerequisite behavior.');
  await expect(entry(region(page, 'Page list'), pageA)).toHaveCount(1);
  await page.reload();
  await heading(page, chapter);
  await expect(entry(region(page, 'Page list'), pageA)).toHaveCount(1);
});
